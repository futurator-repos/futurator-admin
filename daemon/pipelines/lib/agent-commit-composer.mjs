/**
 * agent-commit-composer.mjs — Story 19.5 (party-push Epic 19 shared substrate).
 *
 * One helper for composing canonical commit messages with v2.5 §23 trailers,
 * shared by pipeline-v2's per-story commits AND party-push checkpoints
 * (Story 20.2). Single composer means a future trailer addition or rename
 * lands once and propagates to both agent classes.
 *
 * Output shapes:
 *
 *   Pipeline (kind: 'pipeline'):
 *     story: <storyId> — <title>
 *
 *     <body summary, one paragraph per intent>
 *
 *     Agent: DEV
 *     Plan-Id: <id>
 *     Plan: <slug>
 *     Epic-Id: <id>
 *     Wave: <n>
 *     Story: <id>
 *     [Skills-Used: …]
 *     [Skills-Manifest-Sha: …]
 *
 *     🤖 Generated with Claude Code via the Futurator pipeline
 *
 *   Party (kind: 'party'):
 *     party(<projectId>/round-<N>): <title>
 *
 *     <body summary>
 *
 *     Agent: PARTY-ORCHESTRATOR
 *     Session-Id: <id>
 *     Project: <projectId>
 *     Round: <N>
 *     Trigger: <trigger>
 *     [Debate: <topic>]
 *     [Participants: <name>, <name>, …]
 *
 *     Co-authored-by: BMad Master (Party) <party+bmad-master@futurator.ai>
 *     Co-authored-by: <name> (Party) <party+<slug>@futurator.ai>
 *
 *     🤖 Generated by Futurator Party Mode
 *
 * Why a separate `coAuthors` array in the return value: callers using
 * `git commit -F -` can append the whole message; callers using
 * `git commit -m "$subject" -m "$body" ...` may prefer to pass co-authors
 * via additional `-m` flags. Both work because the message already
 * includes the trailers.
 */

const NOISE_TITLE_PATTERNS = [
  /^update$/i,
  /^updates$/i,
  /^change$/i,
  /^changes$/i,
  /^fix$/i,
  /^fixes$/i,
  /^wip$/i,
  /^untitled$/i,
];

/**
 * Strip C0 control chars (0x00–0x1f) except newline (0x0a) and tab (0x09),
 * DEL (0x7f), and zero-width Unicode characters (U+200B–U+200F, U+FEFF) plus
 * trailing whitespace. §12.1.3 fix — pre-fix the regex left zero-width
 * joiners and BOM through, which would break `git log --grep` queries and
 * silently corrupt the trailer block.
 *
 * Newlines are kept because legitimate commit bodies contain paragraphs;
 * callers that need a one-line value (subject, trailer values) trim or
 * collapse downstream. Tab is kept for indented code blocks in bodies.
 */
export function sanitize(s) {
  if (s === undefined || s === null) return '';
  return String(s)
    .replace(/[\x00-\x08\x0b-\x1f\x7f]/g, '')
    .replace(/[​-‏﻿]/g, '')
    .replace(/\s+$/g, '');
}

/**
 * Validate a commit subject's title fragment. Returns `clean` (sanitized
 * + trimmed) and a list of warning codes:
 *   - `title-empty` — title is empty after sanitize
 *   - `title-noise` — title matches a known noise pattern (Update / Fix / WIP / …)
 *   - `title-too-short` — fewer than 3 whitespace-separated words after sanitize
 *
 * Warnings do NOT prevent composing the commit — they let the caller
 * decide whether to push a checkpoint event (`party.checkpoint.fallback`
 * per Free Explorer §13.6) instead of (or alongside) the commit.
 */
export function validateTitle(title) {
  const clean = sanitize(title).trim();
  const warnings = [];
  if (clean.length === 0) {
    warnings.push('title-empty');
    return { clean, warnings };
  }
  if (NOISE_TITLE_PATTERNS.some((re) => re.test(clean))) {
    warnings.push('title-noise');
  }
  const wordCount = clean.split(/\s+/).filter(Boolean).length;
  if (wordCount < 3) warnings.push('title-too-short');
  return { clean, warnings };
}

/**
 * Validate a commit body. Returns `clean` (sanitized, line-by-line) and
 * `lines` (the cleaned lines array). Body validation is lighter than title
 * validation — we accept anything that survives sanitize. Empty body is OK.
 */
export function validateSummary(summary) {
  const clean = sanitize(summary);
  if (clean.length === 0) return { clean: '', lines: [] };
  const lines = clean.split('\n').map((l) => l.replace(/\s+$/g, ''));
  return { clean: lines.join('\n'), lines };
}

/**
 * Slugify a participant name for the co-author email local-part. Pulls
 * lowercase ASCII + numbers, replaces everything else with `-`, collapses
 * repeats, trims edges. "John (PM)" → "john-pm".
 */
function slugifyParticipant(name) {
  return sanitize(name)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .replace(/-{2,}/g, '-');
}

/**
 * Build co-author lines for party-mode participants. BMad Master is always
 * first (it orchestrates the debate). Participants list order is preserved
 * after that.
 *
 * Collision case: two participants slugify to the same key (e.g., "John"
 * and "John (PM)" both → "john"… wait, "John (PM)" → "john-pm" — so the
 * collision is "John" and "John" duplicates, or near-misses like "DEV"
 * and "dev"). When collision detected, the first wins, the rest get a
 * `coauthor-collision` warning so the caller can decide policy.
 */
function buildCoAuthors(participants) {
  const warnings = [];
  const seen = new Set();
  const lines = [];
  // BMad Master always present, always first.
  lines.push('Co-authored-by: BMad Master (Party) <party+bmad-master@futurator.ai>');
  seen.add('bmad-master');

  for (const raw of participants || []) {
    const cleanName = sanitize(raw).trim();
    if (!cleanName) continue;
    const slug = slugifyParticipant(cleanName) || 'participant';
    if (seen.has(slug)) {
      warnings.push(`coauthor-collision:${slug}`);
      continue;
    }
    seen.add(slug);
    lines.push(`Co-authored-by: ${cleanName} (Party) <party+${slug}@futurator.ai>`);
  }
  return { lines, warnings };
}

/**
 * @typedef {object} PipelineV2Input
 * @property {'pipeline'} kind
 * @property {string} title
 * @property {string} summary
 * @property {string} storyId
 * @property {string} planId
 * @property {string} plan
 * @property {string} epicId
 * @property {string | number} wave
 * @property {string} [agent]   - default 'DEV'
 * @property {string} [skillsUsed]
 * @property {string} [skillsManifestSha]
 *
 * @typedef {object} PartyInput
 * @property {'party'} kind
 * @property {string} title
 * @property {string} summary
 * @property {string} sessionId
 * @property {string} projectId
 * @property {number} round
 * @property {string} trigger
 * @property {string} [debate]
 * @property {string[]} [participants]
 *
 * @typedef {object} ComposeResult
 * @property {string} message
 * @property {string[]} coAuthors
 * @property {string[]} warnings
 */

/**
 * Compose a commit message for either pipeline-v2 or party-push.
 *
 * @param {PipelineV2Input | PartyInput} input
 * @returns {ComposeResult}
 */
export function composeAgentCommit(input) {
  if (!input || typeof input !== 'object') {
    throw new Error('composeAgentCommit: input is required');
  }
  if (input.kind !== 'pipeline' && input.kind !== 'party') {
    throw new Error(`composeAgentCommit: unknown kind '${input.kind}'`);
  }

  const titleResult = validateTitle(input.title);
  const summaryResult = validateSummary(input.summary);
  const warnings = [...titleResult.warnings];

  if (input.kind === 'pipeline') {
    const subject = `story: ${sanitize(input.storyId)} — ${titleResult.clean || '(untitled)'}`;
    const body = summaryResult.clean;
    const trailers = [
      `Agent: ${sanitize(input.agent || 'DEV')}`,
      `Plan-Id: ${sanitize(input.planId)}`,
      `Plan: ${sanitize(input.plan)}`,
      `Epic-Id: ${sanitize(input.epicId)}`,
      `Wave: ${sanitize(String(input.wave))}`,
      `Story: ${sanitize(input.storyId)}`,
    ];
    if (input.skillsUsed) trailers.push(`Skills-Used: ${sanitize(input.skillsUsed)}`);
    if (input.skillsManifestSha) {
      trailers.push(`Skills-Manifest-Sha: ${sanitize(input.skillsManifestSha)}`);
    }
    const footer = '🤖 Generated with Claude Code via the Futurator pipeline';
    const message = [subject, '', body, '', trailers.join('\n'), '', footer]
      .join('\n')
      .replace(/\n{3,}/g, '\n\n')
      .trim();
    return { message, coAuthors: [], warnings };
  }

  // input.kind === 'party'
  const subject = `party(${sanitize(input.projectId)}/round-${input.round}): ${
    titleResult.clean || '(untitled)'
  }`;
  const body = summaryResult.clean;
  const trailers = [
    'Agent: PARTY-ORCHESTRATOR',
    `Session-Id: ${sanitize(input.sessionId)}`,
    `Project: ${sanitize(input.projectId)}`,
    `Round: ${input.round}`,
    `Trigger: ${sanitize(input.trigger)}`,
  ];
  if (input.debate) trailers.push(`Debate: ${sanitize(input.debate)}`);
  const participants = (input.participants || [])
    .map((p) => sanitize(p).trim())
    .filter(Boolean);
  if (participants.length > 0) {
    trailers.push(`Participants: ${participants.join(', ')}`);
  }

  const { lines: coAuthorLines, warnings: coAuthorWarnings } = buildCoAuthors(participants);
  warnings.push(...coAuthorWarnings);

  const footer = '🤖 Generated by Futurator Party Mode';
  const segments = [subject, '', body, '', trailers.join('\n'), '', coAuthorLines.join('\n'), '', footer];
  const message = segments
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
  return { message, coAuthors: coAuthorLines, warnings };
}
