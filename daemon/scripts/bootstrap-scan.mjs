// ── Source File Analysis ──

/**
 * Analyze a source file and extract metadata for wiki article generation.
 */
function analyzeFile(filePath, rootDir) {
  let content;
  try {
    content = readFileSync(filePath, 'utf-8');
  } catch (err) {
    log('warn', `Cannot read file: ${filePath}`, { error: err.message });
    return null;
  }

  const relPath = relative(rootDir, filePath);
  const ext = extname(filePath);
  const lines = content.split('\n');

  const analysis = {
    relPath,
    slug: toSlug(relPath),
    ext,
    lineCount: lines.length,
    content,
    purpose: '',
    exports: [],
    imports: [],
    tags: [],
  };

  // Infer purpose from file location and content
  analysis.purpose = inferPurpose(relPath, content, ext);

  // Extract exports
  analysis.exports = extractExports(content, ext);

  // Extract imports (preliminary — refined in Story 6.2)
  analysis.imports = extractImports(content, ext);

  // Infer tags from path and content
  analysis.tags = inferTags(relPath, content, ext);

  return analysis;
}

/**
 * Infer the purpose of a file from its path and content.
 */
function inferPurpose(relPath, content, ext) {
  const parts = relPath.split(sep);
  const fileName = parts[parts.length - 1];
  const dirName = parts.length > 1 ? parts[parts.length - 2] : '';

  // Check for JSDoc/docstring at top of file
  const topComment = extractTopComment(content, ext);
  if (topComment) return topComment;

  // Infer from path patterns
  const pathLower = relPath.toLowerCase();
  if (pathLower.includes('component')) return `React component in ${dirName}/ directory.`;
  if (pathLower.includes('hook') || fileName.startsWith('use')) return `Custom React hook.`;
  if (pathLower.includes('util') || pathLower.includes('helper')) return `Utility functions for ${dirName}.`;
  if (pathLower.includes('api') || pathLower.includes('route')) return `API route/endpoint handler.`;
  if (pathLower.includes('model') || pathLower.includes('schema')) return `Data model/schema definition.`;
  if (pathLower.includes('test') || pathLower.includes('spec')) return `Test file for ${dirName} module.`;
  if (pathLower.includes('config')) return `Configuration file.`;
  if (pathLower.includes('middleware')) return `Middleware handler.`;
  if (pathLower.includes('context') || pathLower.includes('provider')) return `React context provider.`;
  if (pathLower.includes('service')) return `Service layer for business logic.`;
  if (pathLower.includes('type') || pathLower.includes('interface')) return `TypeScript type definitions.`;
  if (pathLower.includes('style') || ext === '.css' || ext === '.scss') return `Stylesheet for ${dirName}.`;
  if (fileName === 'package.json') return `Package manifest defining project dependencies and scripts.`;
  if (fileName === 'tsconfig.json') return `TypeScript compiler configuration.`;
  if (ext === '.md') return `Documentation file.`;

  return `Source file at ${relPath}.`;
}

/**
 * Extract the top-level comment/docstring from a file.
 */
function extractTopComment(content, ext) {
  if (['.ts', '.tsx', '.js', '.jsx', '.mjs', '.cjs'].includes(ext)) {
    // Match /** ... */ block comments at top
    const match = content.match(/^\s*\/\*\*\s*\n([\s\S]*?)\*\//);
    if (match) {
      return match[1]
        .split('\n')
        .map(l => l.replace(/^\s*\*\s?/, '').trim())
        .filter(l => l && !l.startsWith('@'))
        .join(' ')
        .slice(0, 300);
    }
    // Match // comments at top
    const lineComments = [];
    for (const line of content.split('\n').slice(0, 10)) {
      const m = line.match(/^\s*\/\/\s?(.*)/);
      if (m && m[1].trim()) lineComments.push(m[1].trim());
      else if (line.trim() && !line.match(/^\s*\/\//)) break;
    }
    if (lineComments.length > 0) return lineComments.join(' ').slice(0, 300);
  }

  if (ext === '.py') {
    // Match triple-quoted docstrings
    const match = content.match(/^\s*(?:#.*\n)*\s*(?:"""([\s\S]*?)"""|'''([\s\S]*?)''')/);
    if (match) {
      return (match[1] || match[2]).trim().split('\n').map(l => l.trim()).join(' ').slice(0, 300);
    }
  }

  return null;
}

/**
 * Extract exported symbols from source code.
 */
function extractExports(content, ext) {
  const exports = [];

  if (['.ts', '.tsx', '.js', '.jsx', '.mjs', '.cjs'].includes(ext)) {
    // export default
    const defaultMatch = content.match(/export\s+default\s+(?:function|class|const|let|var)?\s*(\w+)/);
    if (defaultMatch) exports.push({ name: defaultMatch[1], kind: 'default' });

    // export function/const/class
    const namedRegex = /export\s+(?:async\s+)?(?:function|const|let|var|class|interface|type|enum)\s+(\w+)/g;
    let m;
    while ((m = namedRegex.exec(content)) !== null) {
      if (!exports.find(e => e.name === m[1])) {
        exports.push({ name: m[1], kind: 'named' });
      }
    }

    // export { ... }
    const reExportMatch = content.match(/export\s*\{([^}]+)\}/g);
    if (reExportMatch) {
      for (const re of reExportMatch) {
        const inner = re.match(/\{([^}]+)\}/);
        if (inner) {
          for (const sym of inner[1].split(',')) {
            const name = sym.trim().split(/\s+as\s+/)[0].trim();
            if (name && !exports.find(e => e.name === name)) {
              exports.push({ name, kind: 're-export' });
            }
          }
        }
      }
    }
  }

  if (ext === '.py') {
    // def / class at module level
    const defRegex = /^(?:def|class|async\s+def)\s+(\w+)/gm;
    let m;
    while ((m = defRegex.exec(content)) !== null) {
      if (!m[1].startsWith('_')) {
        exports.push({ name: m[1], kind: 'function/class' });
      }
    }
  }

  return exports.slice(0, 20); // Limit to top 20 exports
}

/**
 * Extract import statements (preliminary — refined in Story 6.2).
 */
function extractImports(content, ext) {
  const imports = [];

  if (['.ts', '.tsx', '.js', '.jsx', '.mjs', '.cjs'].includes(ext)) {
    // import ... from '...'
    const importFromRegex = /import\s+(?:[\s\S]*?)\s+from\s+['"]([^'"]+)['"]/g;
    let m;
    while ((m = importFromRegex.exec(content)) !== null) {
      imports.push({ source: m[1], kind: 'import' });
    }

    // require('...')
    const requireRegex = /require\s*\(\s*['"]([^'"]+)['"]\s*\)/g;
    while ((m = requireRegex.exec(content)) !== null) {
      imports.push({ source: m[1], kind: 'require' });
    }

    // import '...' (side-effect imports)
    const sideEffectRegex = /import\s+['"]([^'"]+)['"]/g;
    while ((m = sideEffectRegex.exec(content)) !== null) {
      if (!imports.find(i => i.source === m[1])) {
        imports.push({ source: m[1], kind: 'side-effect' });
      }
    }
  }

  if (ext === '.py') {
    // import X / from X import Y
    const pyImportRegex = /^(?:from\s+([\w.]+)\s+import|import\s+([\w.]+))/gm;
    let m;
    while ((m = pyImportRegex.exec(content)) !== null) {
      imports.push({ source: m[1] || m[2], kind: 'python' });
    }
  }

  if (ext === '.css' || ext === '.scss') {
    // @import '...' / @use '...'
    const cssImportRegex = /@(?:import|use)\s+['"]([^'"]+)['"]/g;
    let m;
    while ((m = cssImportRegex.exec(content)) !== null) {
      imports.push({ source: m[1], kind: 'css' });
    }
  }

  return imports;
}

/**
 * Infer tags from file path and content.
 */
function inferTags(relPath, content, ext) {
  const tags = new Set();
  const pathLower = relPath.toLowerCase();

  // Extension-based tags
  if (['.ts', '.tsx'].includes(ext)) tags.add('typescript');
  if (['.js', '.jsx', '.mjs', '.cjs'].includes(ext)) tags.add('javascript');
  if (ext === '.py') tags.add('python');
  if (ext === '.css' || ext === '.scss') tags.add('styles');
  if (ext === '.md') tags.add('documentation');
  if (ext === '.json') tags.add('config');
  if (ext === '.yaml' || ext === '.yml') tags.add('config');
  if (ext === '.html') tags.add('html');
  if (ext === '.sh') tags.add('shell');

  // Path-based tags
  if (pathLower.includes('component')) tags.add('component');
  if (pathLower.includes('hook') || basename(relPath).startsWith('use')) tags.add('hook');
  if (pathLower.includes('api') || pathLower.includes('route')) tags.add('api');
  if (pathLower.includes('test') || pathLower.includes('spec')) tags.add('test');
  if (pathLower.includes('util') || pathLower.includes('helper')) tags.add('utility');
  if (pathLower.includes('config')) tags.add('config');
  if (pathLower.includes('middleware')) tags.add('middleware');
  if (pathLower.includes('context') || pathLower.includes('provider')) tags.add('context');
  if (pathLower.includes('service')) tags.add('service');
  if (pathLower.includes('model') || pathLower.includes('schema')) tags.add('model');
  if (pathLower.includes('type') || pathLower.includes('interface')) tags.add('types');
  if (pathLower.includes('style')) tags.add('styles');
  if (pathLower.includes('layout')) tags.add('layout');
  if (pathLower.includes('page')) tags.add('page');

  // Content-based tags
  if (content.includes('useState') || content.includes('useEffect')) tags.add('react');
  if (content.includes('express')) tags.add('express');
  if (content.includes('Next') || content.includes('next/')) tags.add('nextjs');
  if (content.includes('prisma')) tags.add('prisma');
  if (content.includes('jwt') || content.includes('JWT')) tags.add('authentication');
  if (content.includes('DynamoDB') || content.includes('dynamodb')) tags.add('dynamodb');
  if (content.includes('S3') || content.includes('s3')) tags.add('s3');
  if (content.includes('Lambda') || content.includes('lambda')) tags.add('lambda');

  return [...tags].slice(0, 10);
}

// ── Article Generation ──

/**
 * Generate preliminary wikilinks from imports.
 * Maps relative imports to wiki article slugs.
 */
function importsToWikilinks(imports, relPath, rootDir, allFilePaths) {
  const links = [];
  const fileDir = dirname(relPath);

  for (const imp of imports) {
    // Only resolve relative/internal imports
    if (!imp.source.startsWith('.') && !imp.source.startsWith('/')) continue;

    // Resolve relative path
    let resolved = join(fileDir, imp.source).replace(/\\/g, '/');
    // Normalize: remove leading ./
    if (resolved.startsWith('./')) resolved = resolved.slice(2);

    // Try to find matching file (with extension resolution)
    const match = resolveImportPath(resolved, allFilePaths);
    if (match) {
      const slug = toSlug(match);
      links.push({ slug, source: imp.source });
    }
  }

  return links;
}

/**
 * Resolve an import path to an actual file path from the known file list.
 */
function resolveImportPath(importPath, allFilePaths) {
  // Direct match
  if (allFilePaths.has(importPath)) return importPath;

  // Try adding extensions
  const extensions = ['.ts', '.tsx', '.js', '.jsx', '.mjs', '.cjs'];
  for (const ext of extensions) {
    if (allFilePaths.has(importPath + ext)) return importPath + ext;
  }

  // Try as directory with index file
  for (const ext of extensions) {
    const indexPath = `${importPath}/index${ext}`;
    if (allFilePaths.has(indexPath)) return indexPath;
  }

  return null;
}

/**
 * Generate a wiki article markdown string for a source file.
 */
function generateArticle(analysis, wikilinks, projectId) {
  const dateStr = today();
  const tagsStr = analysis.tags.length > 0 ? `[${analysis.tags.join(', ')}]` : '[]';

  // Build exports section
  let exportsSection = '_No exports detected._';
  if (analysis.exports.length > 0) {
    exportsSection = analysis.exports
      .map(e => `- \`${e.name}\` — ${e.kind} export`)
      .join('\n');
  }

  // Build dependencies section (preliminary wikilinks)
  let depsSection = '_Dependencies will be refined in dependency extraction pass._';
  if (wikilinks.length > 0) {
    depsSection = wikilinks
      .map(l => `- [[${toArticlePath(l.slug)}]] — imported as \`${l.source}\``)
      .join('\n');
  }

  // Build external dependencies
  const externalImports = analysis.imports.filter(i =>
    !i.source.startsWith('.') && !i.source.startsWith('/')
  );
  let externalDepsSection = '';
  if (externalImports.length > 0) {
    externalDepsSection = '\n## External Dependencies\n\n' +
      externalImports.map(i => `- \`${i.source}\``).join('\n') + '\n';
  }

  const article = `---
title: ${analysis.relPath}
type: code
phase: implementation
status: active
maturity: 0.5
created: ${dateStr}
updated: ${dateStr}
createdByEpic: bootstrap
createdByStory: bootstrap-scan
tags: ${tagsStr}
---

## Purpose

${analysis.purpose}

## Key Exports

${exportsSection}

## Dependencies

${depsSection}

## Dependents

_Dependents will be populated in dependency extraction pass._
${externalDepsSection}
## Signals

- File contains ${analysis.lineCount} lines of ${analysis.ext.slice(1)} code
- ${analysis.exports.length} exported symbol(s) detected
- ${analysis.imports.length} import statement(s) detected

## Missing Signals

- Detailed behavioral analysis not yet performed
- Test coverage unknown
- Performance characteristics not assessed
`;

  return article;
}

