// ── Configuration ──

const SUPPORTED_EXTENSIONS = new Set([
  '.ts', '.tsx', '.js', '.jsx', '.mjs', '.cjs',
  '.py',
  '.md',
  '.json',
  '.yaml', '.yml',
  '.sh',
  '.css', '.scss', '.html',
]);

const EXCLUDED_DIRS = new Set([
  'node_modules', '.git', 'dist', 'build', '.next', 'coverage',
  '.mycelium', 'knowledge', '__pycache__', '.cache', '.turbo',
  '.vercel', '.output', '.nuxt', '.svelte-kit', 'out',
  '.pytest_cache', '.tox', 'venv', '.venv', 'env',
]);

const DEFAULT_BATCH_SIZE = 20;

// ── Wiki directory structure ──

const WIKI_DIRS = [
  'code', 'decisions', 'requirements', 'discovery',
  'planning', 'solutioning', 'qa', 'system', 'archive',
];

// ── Helpers ──

function log(level, msg, data = {}) {
  const prefix = {
    info: '\x1b[36mINFO\x1b[0m',
    warn: '\x1b[33mWARN\x1b[0m',
    error: '\x1b[31mERROR\x1b[0m',
    debug: '\x1b[90mDEBG\x1b[0m',
  };
  const ts = new Date().toISOString();
  const extra = Object.keys(data).length ? ` ${JSON.stringify(data)}` : '';
  console.log(`[${ts}] ${prefix[level] || level} [bootstrap-scan] ${msg}${extra}`);
}

function toSlug(filePath) {
  // Convert path separators to -- for wiki slug
  return filePath.replace(/\//g, '--').replace(/\\/g, '--');
}

function toArticlePath(slug) {
  return `code/${slug}`;
}

function today() {
  return new Date().toISOString().split('T')[0];
}

// ── File Discovery ──

/**
 * Recursively discover all relevant source files, excluding generated directories.
 */
function discoverFiles(rootDir) {
  const files = [];

  function walk(dir) {
    let entries;
    try {
      entries = readdirSync(dir, { withFileTypes: true });
    } catch (err) {
      log('warn', `Cannot read directory: ${dir}`, { error: err.message });
      return;
    }

    for (const entry of entries) {
      const fullPath = join(dir, entry.name);

      if (entry.isDirectory()) {
        if (!EXCLUDED_DIRS.has(entry.name)) {
          walk(fullPath);
        }
        continue;
      }

      if (entry.isFile()) {
        const ext = extname(entry.name);
        if (SUPPORTED_EXTENSIONS.has(ext)) {
          files.push(fullPath);
        }
      }
    }
  }

  walk(rootDir);
  return files;
}

/**
 * Sort files by directory depth (shallow first) for better dependency context.
 */
function sortByDepth(files, rootDir) {
  return files.sort((a, b) => {
    const relA = relative(rootDir, a);
    const relB = relative(rootDir, b);
    const depthA = relA.split(sep).length;
    const depthB = relB.split(sep).length;
    if (depthA !== depthB) return depthA - depthB;
    return relA.localeCompare(relB);
  });
}

/**
 * Split array into batches of given size.
 */
function chunk(arr, size) {
  const batches = [];
  for (let i = 0; i < arr.length; i += size) {
    batches.push(arr.slice(i, i + size));
  }
  return batches;
}

