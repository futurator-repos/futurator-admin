// ── Main Bootstrap Scan ──

/**
 * Main bootstrap scan function.
 *
 * @param {string} projectId - Project identifier (e.g., "spyhunter")
 * @param {string} workingDir - Absolute path to project root
 * @param {object} opts - Options
 * @param {number} opts.batchSize - Files per batch (default 20)
 * @param {boolean} opts.json - Output JSON results
 * @param {function} opts.onProgress - Progress callback
 * @returns {object} Scan results with manifest
 */
export async function bootstrapScan(projectId, workingDir, opts = {}) {
  const startTime = Date.now();
  const batchSize = opts.batchSize || DEFAULT_BATCH_SIZE;
  const errors = [];

  log('info', `Starting bootstrap scan for project "${projectId}"`, { workingDir, batchSize });

  // Step 1: Initialize wiki structure
  const knowledgeDir = initWikiStructure(workingDir, projectId);

  // Step 2: Discover files
  log('info', 'Discovering source files...');
  const allFiles = discoverFiles(workingDir);
  const sortedFiles = sortByDepth(allFiles, workingDir);
  const relPaths = sortedFiles.map(f => relative(workingDir, f));

  log('info', `Discovered ${sortedFiles.length} source files`);

  emitEvent({
    type: 'progress',
    stage: 'scan',
    message: `Discovered ${sortedFiles.length} files`,
    totalFiles: sortedFiles.length,
  });

  // Build a set of all relative paths for import resolution
  const allRelPathsSet = new Set(relPaths);

  // Step 3: Process files in batches
  const batches = chunk(sortedFiles, batchSize);
  const manifest = {
    projectId,
    workingDir,
    scanDate: new Date().toISOString(),
    batchSize,
    totalBatches: batches.length,
    scannedFiles: [],
    fileCount: sortedFiles.length,
    articleCount: 0,
    errors: [],
  };

  let filesProcessed = 0;

  for (let batchIdx = 0; batchIdx < batches.length; batchIdx++) {
    const batch = batches[batchIdx];
    log('info', `Processing batch ${batchIdx + 1}/${batches.length} (${batch.length} files)`);

    for (const filePath of batch) {
      const relPath = relative(workingDir, filePath);
      const slug = toSlug(relPath);
      const articlePath = join(knowledgeDir, 'code', `${slug}.md`);

      try {
        // Analyze source file
        const analysis = analyzeFile(filePath, workingDir);
        if (!analysis) {
          errors.push({ file: relPath, error: 'Could not read file' });
          manifest.errors.push({ file: relPath, error: 'Could not read file' });
          continue;
        }

        // Generate preliminary wikilinks from imports
        const wikilinks = importsToWikilinks(analysis.imports, relPath, workingDir, allRelPathsSet);

        // Generate article
        const article = generateArticle(analysis, wikilinks, projectId);

        // Write article to knowledge/code/
        writeFileSync(articlePath, article, 'utf-8');

        manifest.scannedFiles.push({
          sourcePath: relPath,
          articlePath: `knowledge/code/${slug}.md`,
          slug: `code/${slug}`,
          lineCount: analysis.lineCount,
          exports: analysis.exports.length,
          imports: analysis.imports.length,
        });
        manifest.articleCount++;

      } catch (err) {
        log('error', `Failed to process file: ${relPath}`, { error: err.message });
        errors.push({ file: relPath, error: err.message });
        manifest.errors.push({ file: relPath, error: err.message });
      }

      filesProcessed++;
    }

    // Emit batch progress
    emitEvent({
      type: 'progress',
      stage: 'scan',
      batch: batchIdx + 1,
      total: batches.length,
      filesProcessed,
      totalFiles: sortedFiles.length,
      percentage: Math.round((filesProcessed / sortedFiles.length) * 100),
    });

    if (opts.onProgress) {
      opts.onProgress({
        batch: batchIdx + 1,
        totalBatches: batches.length,
        filesProcessed,
        totalFiles: sortedFiles.length,
      });
    }
  }

  // Step 4: Generate index.md
  generateIndex(knowledgeDir, manifest, projectId);

  // Step 5: Update log.md
  const durationMs = Date.now() - startTime;
  appendLog(knowledgeDir, {
    operation: 'bootstrap-scan',
    projectId,
    timestamp: new Date().toISOString(),
    fileCount: manifest.fileCount,
    articleCount: manifest.articleCount,
    errorCount: errors.length,
    durationMs,
    batchSize,
    totalBatches: batches.length,
  });

  // Step 6: Write bootstrap manifest
  manifest.durationMs = durationMs;
  const manifestPath = join(workingDir, '.mycelium', 'bootstrap-manifest.json');
  mkdirSync(dirname(manifestPath), { recursive: true });
  writeFileSync(manifestPath, JSON.stringify(manifest, null, 2), 'utf-8');

  log('info', `Bootstrap scan complete`, {
    articleCount: manifest.articleCount,
    fileCount: manifest.fileCount,
    errors: errors.length,
    durationMs,
  });

  emitEvent({
    type: 'complete',
    stage: 'scan',
    articleCount: manifest.articleCount,
    fileCount: manifest.fileCount,
    durationMs,
    errors: errors.length,
  });

  return manifest;
}

/**
 * Generate the knowledge/index.md catalog of all articles.
 */
function generateIndex(knowledgeDir, manifest, projectId) {
  const dateStr = today();

  const tableRows = manifest.scannedFiles
    .map(f => `| ${f.sourcePath} | code | implementation | active | \`${f.articlePath}\` |`)
    .join('\n');

  const content = `---
title: Knowledge Index — ${projectId}
type: system
phase: system
status: active
created: ${dateStr}
updated: ${dateStr}
---

# Knowledge Index

_Auto-generated by the brownfield bootstrap pipeline._

**Total Articles:** ${manifest.articleCount}
**Scan Date:** ${manifest.scanDate}
**Project:** ${projectId}

## Articles

| Title | Type | Phase | Status | Path |
|-------|------|-------|--------|------|
${tableRows}
`;

  writeFileSync(join(knowledgeDir, 'index.md'), content, 'utf-8');
  log('info', `Generated index.md with ${manifest.articleCount} entries`);
}

/**
 * Append an entry to knowledge/log.md.
 */
function appendLog(knowledgeDir, entry) {
  const logPath = join(knowledgeDir, 'log.md');
  let existing = '';
  if (existsSync(logPath)) {
    existing = readFileSync(logPath, 'utf-8');
  }

  const logEntry = `
### ${entry.operation} — ${entry.timestamp}

- **Project:** ${entry.projectId}
- **Files Scanned:** ${entry.fileCount}
- **Articles Generated:** ${entry.articleCount}
- **Errors:** ${entry.errorCount}
- **Duration:** ${(entry.durationMs / 1000).toFixed(1)}s
- **Batch Size:** ${entry.batchSize}
- **Total Batches:** ${entry.totalBatches}
`;

  writeFileSync(logPath, existing + logEntry, 'utf-8');
}

// ── CLI Entry Point ──

async function main() {
  const args = process.argv.slice(2);

  let projectId = null;
  let workingDir = null;
  let batchSize = DEFAULT_BATCH_SIZE;
  let jsonOutput = false;

  for (let i = 0; i < args.length; i++) {
    switch (args[i]) {
      case '--project':
        projectId = args[++i];
        break;
      case '--dir':
      case '--working-dir':
        workingDir = args[++i];
        break;
      case '--batch-size':
        batchSize = parseInt(args[++i], 10);
        break;
      case '--json':
        jsonOutput = true;
        break;
      case '--help':
        console.log(`
Usage: node bootstrap-scan.mjs --project <id> --dir <path> [options]

Options:
  --project <id>       Project identifier (e.g., "spyhunter")
  --dir <path>         Path to project root directory
  --batch-size <n>     Files per batch (default: ${DEFAULT_BATCH_SIZE})
  --json               Output results as JSON
  --help               Show this help message
`);
        process.exit(0);
    }
  }

  if (!projectId || !workingDir) {
    console.error('Error: --project and --dir are required');
    console.error('Usage: node bootstrap-scan.mjs --project <id> --dir /path/to/project');
    process.exit(1);
  }

  if (!existsSync(workingDir)) {
    console.error(`Error: Directory not found: ${workingDir}`);
    process.exit(1);
  }

  try {
    const result = await bootstrapScan(projectId, workingDir, { batchSize, json: jsonOutput });

    if (jsonOutput) {
      console.log(JSON.stringify(result, null, 2));
    }
  } catch (err) {
    console.error('Bootstrap scan failed:', err.message);
    if (!jsonOutput) console.error(err.stack);
    process.exit(1);
  }
}

// Run if executed directly
const isDirectExecution = process.argv[1] && (
  process.argv[1].endsWith('bootstrap-scan.mjs') ||
  process.argv[1].endsWith('bootstrap-scan')
);

if (isDirectExecution) {
  main();
}
